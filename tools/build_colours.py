"""picks_colours.txt -> ../data/colours.js. Every colour must be stated in the PDF sentence it cites."""
import json, re, os
HERE = os.path.dirname(os.path.abspath(__file__))
VOCAB = "colourless white black red blue green yellow violet purple orange brown pink grey crimson bronze ruby apple brick pale deep dark greenish yellowish translucent colour".split()
def letters(s): return re.sub(r"[^a-z]", "", s.lower())
srcs = {}
def rows(k):
    if k not in srcs: srcs[k] = {r["id"]: r for r in json.load(open(f"{HERE}/src/{k}.json"))["rows"]}
    return srcs[k]
# which chapter owns each cited sentence: the picks line with the nearest id at or below it
owners = {}
for fn in os.listdir(f"{HERE}/picks"):
    ch = fn[:-4]; key = None
    for l in open(f"{HERE}/picks/{fn}", encoding="utf-8"):
        if l.startswith("@src"): key = l.split()[1]
        m = re.match(r"^([\d+]+)[!T]*\s", l)
        if m and key:
            for i in m.group(1).split("+"): owners.setdefault(key, []).append((int(i), ch))
for k in owners: owners[k].sort()
def owner(k, i):
    if k == "old11" and i < 39: return "g17"  # Unit 8 (redox) sentence about halide tests; nearest home is Group 17
    best = owners[k][0][1]
    for j, ch in owners[k]:
        if j <= i: best = ch
        else: break
    return best
out, bad = [], []
for n, raw in enumerate(open(f"{HERE}/picks_colours.txt", encoding="utf-8"), 1):
    line = raw.strip()
    if not line or line.startswith("#"): continue
    p = line.split("|")
    k, ids, f, name, hexv, grp = p[:6]
    alias = p[6] if len(p) > 6 else None
    ids = [int(x) for x in ids.split("+")]
    R = rows(k)
    text = " ".join(R[i]["text"] for i in ids)
    low = text.lower()
    need = alias if alias else re.split(r"[ (]", f.replace("[", "").replace("]", ""), 1)[0] if not f.startswith("[") else f.split(" ")[0]
    ok_f = letters(need) in letters(text)
    words = [w for w in re.findall(r"[a-z]+", name.lower()) if w in VOCAB]
    ok_c = bool(words) and all(w in low for w in words)
    if not (ok_f and ok_c): bad.append((n, ok_f, ok_c, f, name))
    out.append({"src": k, "ids": ids, "page": R[ids[0]]["page"], "t": f, "name": name, "hex": hexv or None, "grp": grp, "ch": owner(k, ids[0])})
js = "/* Generated by tools/build_colours.py from picks_colours.txt. Each colour is stated in the cited NCERT sentence; hex is only a rendering. */\n(function () {\n  window.RES.addColours(" + json.dumps(out, ensure_ascii=False) + ");\n})();\n"
open(f"{HERE}/../data/colours.js", "w", encoding="utf-8").write(js)
print(len(out), "colours,", len(bad), "flagged")
for b in bad: print("  ", b)
